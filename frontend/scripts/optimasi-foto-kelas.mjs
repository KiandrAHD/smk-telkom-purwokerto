import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Input is the audited extraction manifest; original photos are never overwritten.
const input = process.argv[2];
assert(input, 'Provide the path to photo-audit.json from the ZIP audit.');
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'src/assets/fasilitas/kelas');
await mkdir(output, { recursive: true });
const inventory = JSON.parse(await readFile(input, 'utf8'));
const covers = {
  'A 1.4': 'IMG_2421.jpeg', 'A 2.2': 'IMG_20261013_161445.jpg',
  'A 3.4': 'IMG_20261013_161621.jpg', 'A 3.6': 'IMG_20261013_161743.jpg',
  'B 1.4': 'IMG_20261012_061545.jpg', 'B 1.5': 'IMG_20261012_061318.jpg',
  'B 2.3': 'IMG_2450.jpeg', 'B 2.5': 'IMG_2459.jpeg',
  'C 2.2': 'IMG_2464.jpeg', 'C 3.2': 'IMG_20261012_065812.jpg',
  'D 1.2': 'IMG_20261012_061054.jpg', 'D 2.1': 'IMG_2470.jpeg',
  'D 3.1': 'IMG_20261012_070008.jpg',
};
const manifest = {}, audit = [];
for (const [room, cover] of Object.entries(covers)) {
  const photos = inventory.filter(photo => {
    const folder = photo.source.split('/')[1].replace(/\s/g, '');
    return folder === room.replace(/\s/g, '') && (room !== 'C 2.2' || photo.source.endsWith('.jpeg'));
  }).sort((a, b) => a.source.localeCompare(b.source));
  const coverIndex = photos.findIndex(photo => path.basename(photo.source) === cover);
  assert(coverIndex >= 0, `${room}: cover absent`);
  photos.unshift(...photos.splice(coverIndex, 1));
  manifest[`Kelas ${room}`] = [];
  for (const photo of photos) {
    const id = `kelas-${room.toLowerCase().replace(/\s/g, '-').replace('.', '-')}-${path.basename(photo.source, path.extname(photo.source)).toLowerCase()}`;
    const variants = [];
    for (const width of [320, 640, 960, 1280]) {
      assert(width <= photo.displayWidth, `${photo.source}: no upscaling`);
      const file = `${id}-${width}.webp`;
      const result = await sharp(photo.path).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: width >= 960 ? 82 : 78, effort: 5 }).toFile(path.join(output, file));
      assert.equal(result.width, width);
      assert.equal(result.height, width * 3 / 4);
      variants.push({ file, width: result.width, height: result.height, bytes: result.size });
    }
    manifest[`Kelas ${room}`].push({ id, source: photo.source });
    audit.push({ name: `Kelas ${room}`, source: photo.source, sha256: photo.sha256, originalBytes: photo.bytes, width: photo.displayWidth, height: photo.displayHeight, variants });
  }
}
assert.equal(Object.keys(manifest).length, 13);
assert.equal(audit.length, 91);
assert.equal(new Set(audit.map(photo => photo.sha256)).size, 91);
await writeFile(path.join(root, 'src/data/classroomPhotoManifest.json'), JSON.stringify(manifest, null, 2) + '\n');
let coverCode = '// Generated by scripts/optimasi-foto-kelas.mjs; gallery assets load separately.\n';
const coverEntries = Object.entries(manifest).map(([name, photos], index) => {
  const photo = photos[0];
  for (const width of [320, 640, 960, 1280]) coverCode += `import p${index}_${width} from '../assets/fasilitas/kelas/${photo.id}-${width}.webp';\n`;
  return `${JSON.stringify(name)}: [{ source: ${JSON.stringify(photo.source)}, src: p${index}_1280, thumbnail: p${index}_320, width: 1280, height: 960, srcSet: \`${[320, 640, 960, 1280].map(width => '${p' + index + '_' + width + '} ' + width + 'w').join(', ')}\` }]`;
});
await writeFile(path.join(root, 'src/data/classroomPhotoCovers.js'), coverCode + `\nexport const classroomPhotoCovers = {\n${coverEntries.join(',\n')}\n};\n`);
await writeFile(path.join(root, 'docs/foto-kelas-integrasi.json'), JSON.stringify(audit, null, 2) + '\n');
console.log(`Optimized ${audit.length} photos for 13 rooms into ${audit.length * 4} responsive WebP files.`);
